"""Generate OpenCV DICT_4X4_50 data and detectable PNG previews.

Install: python -m pip install -r requirements.txt
Run:     python generate_dict.py
Outputs are relative to this script, independent of the working directory.
"""
from pathlib import Path

import cv2

DICT_NAME = "DICT_4X4_50"
OUT_FILE = Path(__file__).resolve().with_name("aruco_dict_4x4_50.js")
PREVIEW_DIR = OUT_FILE.parent / "preview"
MARKER_SIZE = 4
BORDER_BITS = 1
PX_PER_MODULE = 60


def get_dictionary():
    if not hasattr(cv2, "aruco") or not hasattr(cv2.aruco, "generateImageMarker"):
        raise RuntimeError("OpenCV ArUco unavailable. Install requirements.txt.")
    return cv2.aruco.getPredefinedDictionary(getattr(cv2.aruco, DICT_NAME))


def get_marker_bits(marker_id):
    # Sample the actual reference: 1 means white, 0 means black.
    image = cv2.aruco.generateImageMarker(get_dictionary(), marker_id, 6)
    return (image[1:5, 1:5] > 128).astype(int).reshape(-1).tolist()


def build_javascript():
    dictionary = get_dictionary()
    flat = []
    for marker_id in range(len(dictionary.bytesList)):
        code = 0
        for bit in get_marker_bits(marker_id):
            code = (code << 1) | bit
        flat.extend([code >> 8, code & 255])
    lines = [
        "// Automatically generated by generate_dict.py. Do not edit.",
        f"// OpenCV {DICT_NAME}: {len(dictionary.bytesList)} markers; 1 = white.",
        "const ARUCO_4X4_50_BYTES = new Uint8Array([",
    ]
    for offset in range(0, len(flat), 16):
        lines.append("  " + ", ".join(f"0x{byte:02x}" for byte in flat[offset:offset + 16]) + ",")
    return "\n".join(lines + ["]);", ""])


def save_preview_png(marker_id, path):
    marker = cv2.aruco.generateImageMarker(
        get_dictionary(), marker_id, (MARKER_SIZE + 2 * BORDER_BITS) * PX_PER_MODULE,
        borderBits=BORDER_BITS,
    )
    image = cv2.copyMakeBorder(marker, PX_PER_MODULE, PX_PER_MODULE,
                               PX_PER_MODULE, PX_PER_MODULE,
                               cv2.BORDER_CONSTANT, value=255)
    # imencode + tofile also supports non-ASCII Windows paths.
    ok, encoded = cv2.imencode(".png", image)
    if not ok:
        raise OSError(f"Cannot encode PNG: {path}")
    encoded.tofile(str(path))


def main():
    OUT_FILE.write_text(build_javascript(), encoding="utf-8")
    PREVIEW_DIR.mkdir(exist_ok=True)
    for marker_id in [0, 1, 2, 3, 4, 5, 10, 49]:
        save_preview_png(marker_id, PREVIEW_DIR / f"id_{marker_id}.png")
    print(f"OpenCV {cv2.__version__}: {DICT_NAME}, IDs 0..49")
    print(f"Dictionary: {OUT_FILE}")
    print(f"Previews: {PREVIEW_DIR}")


if __name__ == "__main__":
    main()
